    private static void L(string index, string en, string zhCn, string zhTw)
    {
        MenuAPI.CreateLocalization(index)
            .AddLocalization(en, LocalizedText.Language.English)
            .AddLocalization(zhCn, LocalizedText.Language.SimplifiedChinese)
            .AddLocalization(zhTw, LocalizedText.Language.TraditionalChinese);
    }

    public static string T(string index)
    {
        try
        {
            var text = LocalizedText.GetText(index, printDebug: false);
            if (string.IsNullOrEmpty(text))
                return index;
            return text;
        }
        catch
        {
            return index;
        }
    }

    public static string Tf(string index, params object[] args)
    {
        try
        {
            // Escape braces in arguments (player names may contain '{' / '}'), otherwise
            // string.Format throws or substitutes wrongly and the label degrades to the key).
            if (args != null)
            {
                for (int i = 0; i < args.Length; i++)
                {
                    if (args[i] is string s && (s.IndexOf('{') >= 0 || s.IndexOf('}') >= 0))
                        args[i] = s.Replace("{", "{{").Replace("}", "}}");
                }
            }
            return string.Format(T(index), args);
        }
        catch
        {
            return T(index);
        }
    }

    public static string Relative(System.DateTime utc)
    {
        var span = System.DateTime.UtcNow - utc.ToUniversalTime();
        if (span.TotalMinutes < 1) return T(RelJustNow);
        if (span.TotalHours < 1) return Tf(RelMinutes, System.Math.Max(1, (int)span.TotalMinutes));
        if (span.TotalDays < 1) return Tf(RelHours, System.Math.Max(1, (int)span.TotalHours));
        return Tf(RelDays, System.Math.Max(1, (int)span.TotalDays));
    }
